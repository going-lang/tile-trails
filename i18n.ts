export function getT(lang: LanguageCode | undefined): Translation {
  return { ...EN, ...(DICT[lang || 'EN'] || {}) };
}

/** Replaces {placeholders} inside a translated template */
export function fmt(template: string, vars: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(vars[key] ?? ''));
}
